"""Result and change models."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List


class ChangeType(str, Enum):
    FIELD_ADDED = "FIELD_ADDED"  # new field, new nested field or new array item definition
    ATTRIBUTE_CHANGED = "ATTRIBUTE_CHANGED"  # retrievable / indexable / searchable / root options ...
    KEY_PROPERTY_MAPPING_CHANGED = "KEY_PROPERTY_MAPPING_CHANGED"  # supported by the service
    TYPE_CHANGED = "TYPE_CHANGED"  # type / format change: NOT supported in place by the service


# Per Vertex AI Search docs: changing a field type is not supported on an
# existing schema. Field removal is never generated by this package.
BREAKING_CHANGE_TYPES = frozenset({ChangeType.TYPE_CHANGED})


@dataclass(frozen=True)
class SchemaChange:
    path: str
    change_type: ChangeType
    old: Any = None
    new: Any = None

    @property
    def breaking(self) -> bool:
        return self.change_type in BREAKING_CHANGE_TYPES

    def __str__(self) -> str:
        if self.change_type is ChangeType.FIELD_ADDED:
            return f"+ {self.path}"
        old = "(unset)" if self.old is None else repr(self.old)
        new = "(removed)" if self.new is None else repr(self.new)
        flag = ", BREAKING" if self.breaking else ""
        return f"~ {self.path}: {old} -> {new} ({self.change_type.value}{flag})"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "path": self.path,
            "change_type": self.change_type.value,
            "old": self.old,
            "new": self.new,
            "breaking": self.breaking,
        }


class Action(str, Enum):
    CREATED = "CREATED"  # schema did not exist and was created
    UPDATED = "UPDATED"  # schema existed and was updated in place
    RECREATED = "RECREATED"  # schema deleted + created (empty datastore, breaking change)
    NO_CHANGE = "NO_CHANGE"  # nothing to do (or only skipped breaking changes)
    DRY_RUN = "DRY_RUN"  # changes computed, nothing written


@dataclass
class EvolutionResult:
    action: Action
    schema_name: str
    changes: List[SchemaChange] = field(default_factory=list)  # applied (or planned for DRY_RUN)
    skipped: List[SchemaChange] = field(default_factory=list)  # breaking changes skipped (on_breaking="skip")
    warnings: List[str] = field(default_factory=list)  # e.g. values the service did not persist
    cached: bool = False  # True if answered from the in-process cache

    @property
    def changed(self) -> bool:
        """True if the datastore schema was actually modified."""
        return self.action in (Action.CREATED, Action.UPDATED, Action.RECREATED)

    @property
    def breaking_changes(self) -> List[SchemaChange]:
        return [c for c in (*self.changes, *self.skipped) if c.breaking]

    @property
    def has_breaking(self) -> bool:
        return bool(self.breaking_changes)

    def summary(self) -> str:
        suffix = " (cached)" if self.cached else ""
        lines = [f"[{self.action.value}] {self.schema_name}{suffix}"]
        lines += [f"  {c}" for c in self.changes]
        lines += [f"  SKIPPED {c}" for c in self.skipped]
        lines += [f"  WARNING {w}" for w in self.warnings]
        return "\n".join(lines)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action": self.action.value,
            "schema_name": self.schema_name,
            "changed": self.changed,
            "cached": self.cached,
            "changes": [c.to_dict() for c in self.changes],
            "skipped": [c.to_dict() for c in self.skipped],
            "warnings": list(self.warnings),
        }
